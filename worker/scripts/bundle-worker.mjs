import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const workerRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(workerRoot, "..");
const read = (path) => readFile(resolve(repoRoot, path), "utf8");
const stripImports = (source) => source.replace(/^import .*?;\r?\n/gm, "");
const stripExports = (source) => stripImports(source)
  .replace(/^export default .*?;?\r?\n?/gm, "")
  .replace(/^export (?=(?:async )?function|const|let|var|class)/gm, "");

const contract = stripExports(await read("shared/tao-ai-contract.mjs"));
const prompt = stripExports(await read("worker/src/prompt.mjs"));
const validation = stripExports(await read("worker/src/validation.mjs"));
const gemini = stripExports(await read("worker/src/gemini-provider.mjs"));
const cloudflare = stripExports(await read("worker/src/cloudflare-provider.mjs"));
const index = stripExports(await read("worker/src/index.mjs"));

const bundle = `// Generated by scripts/bundle-worker.mjs — do not edit.\n${contract}\n${prompt}\n${validation}\nconst GeminiProvider = (() => {\n${gemini}\nreturn { callGemini };\n})();\nconst { callGemini } = GeminiProvider;\nconst CloudflareProvider = (() => {\n${cloudflare}\nreturn { callCloudflareAI, CLOUDFLARE_PRIMARY_MODEL, CLOUDFLARE_FALLBACK_MODEL };\n})();\nconst { callCloudflareAI, CLOUDFLARE_PRIMARY_MODEL, CLOUDFLARE_FALLBACK_MODEL } = CloudflareProvider;\n${index}\nexport { createWorkerHandler };\nexport default { fetch: createWorkerHandler() };\n`;

const output = resolve(workerRoot, "dist/index.mjs");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, bundle, "utf8");
console.log(`Worker bundle: ${output}`);
